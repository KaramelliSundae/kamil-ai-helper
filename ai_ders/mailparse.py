"""Mail parsing, kept out of every process that holds a secret.

School mail is untrusted input and the spam filter lets a lot through. So the watcher only downloads
the raw bytes over IMAP. Reading them (MIME, headers, HTML, and above all images, whose decoders are C
code) happens in `python -m ai_ders.mailparse`, which systemd starts once per mail with no network, no
credentials, no writable disk, a memory and time limit and a syscall filter
(deploy/linux/ai-ders-mailparse@.service). It reads one raw mail on stdin and writes JSON on stdout.

Images are decoded only there and re-encoded into fresh JPEGs, so the phone only ever decodes files
this code made, never the sender's. Remote images (http links in the HTML) are never fetched.
"""

from __future__ import annotations

import base64
import binascii
import io
import json
import logging
import socket
import sys
import warnings
from dataclasses import dataclass, field
from datetime import datetime
from typing import Any, Callable

from .models import Attachment
from .text import clean_text, html_to_text

log = logging.getLogger(__name__)

MAX_INPUT_BYTES = 25 * 2**20
MAX_REPLY_BYTES = 40 * 2**20
MAX_ATTACHMENTS = 20
MAX_IMAGES = 6
MAX_IMAGE_BYTES = 15 * 2**20
MAX_PIXELS = 40_000_000
IMAGE_SIDE = 1600
JPEG_QUALITY = 82
IMAGE_FORMATS = ["JPEG", "PNG", "GIF", "WEBP"]
IMAGE_TYPES = {"image/jpeg", "image/jpg", "image/pjpeg", "image/png", "image/gif", "image/webp"}
# The rules only look at these; the rest of the header block never leaves the sandbox.
KEPT_HEADERS = ("precedence", "list-id", "list-unsubscribe", "auto-submitted")
TEXT_LIMITS = {"subject": 1000, "sender": 500, "from": 500, "body": 200_000, "name": 200, "type": 100}


class MailParseError(Exception):
    """This one mail could not be read. The watcher keeps it as unreadable and moves on."""


class SandboxUnavailable(OSError):
    """The sandbox is not there at all. The poll fails and retries, so no mail is lost to an outage."""


@dataclass(frozen=True)
class ParsedMail:
    subject: str
    sender: str  # "Name <address>", for display
    from_: str  # the bare address, for the rules
    date: datetime | None
    body: str
    headers: dict[str, str] = field(default_factory=dict)
    attachments: tuple[Attachment, ...] = ()
    images: dict[str, bytes] = field(default_factory=dict)  # sha256 → clean JPEG


# ---- inside the sandbox ----------------------------------------------------------------------------


def clean_image(data: bytes) -> tuple[bytes, int, int] | None:
    """Decodes an image and draws it into a new JPEG: no metadata, no extra frames, bounded size."""
    from PIL import Image, ImageOps

    if len(data) > MAX_IMAGE_BYTES:
        return None
    Image.MAX_IMAGE_PIXELS = MAX_PIXELS
    try:
        with warnings.catch_warnings():
            warnings.simplefilter("error", Image.DecompressionBombWarning)
            with Image.open(io.BytesIO(data), formats=IMAGE_FORMATS) as source:
                source.draft("RGB", (IMAGE_SIDE, IMAGE_SIDE))
                picture = ImageOps.exif_transpose(source)
                if picture.mode in ("RGBA", "LA", "P", "PA"):
                    rgba = picture.convert("RGBA")
                    picture = Image.new("RGB", rgba.size, "white")
                    picture.paste(rgba, mask=rgba.getchannel("A"))
                else:
                    picture = picture.convert("RGB")
                picture.thumbnail((IMAGE_SIDE, IMAGE_SIDE))
                out = io.BytesIO()
                picture.save(out, "JPEG", quality=JPEG_QUALITY, optimize=True)
                return out.getvalue(), picture.width, picture.height
    except (OSError, ValueError, SyntaxError, EOFError, Image.DecompressionBombError, Image.DecompressionBombWarning):
        return None


def parse(raw: bytes) -> dict[str, Any]:
    """Raw RFC 822 bytes → plain data. Runs in the sandbox."""
    from imap_tools import MailMessage

    message = MailMessage.from_bytes(raw)
    headers = {name.lower(): ", ".join(values) for name, values in message.headers.items()}
    # The HTML part first: the plain part is often generated by the sender's mail program and splits words
    # (Zimbra's plain part reads "Sa ğlıklı" where the HTML says "Sağlıklı").
    body = html_to_text(message.html) or clean_text(message.text)
    date = message.date if message.date and message.date.year > 1900 else None
    attachments: list[dict[str, Any]] = []
    images = 0
    for part in message.attachments[:MAX_ATTACHMENTS]:
        entry: dict[str, Any] = {"name": part.filename or "", "type": (part.content_type or "").lower(), "size": part.size}
        if entry["type"] in IMAGE_TYPES and images < MAX_IMAGES:
            clean = clean_image(part.payload)
            if clean:
                images += 1
                entry |= {"jpeg": base64.b64encode(clean[0]).decode(), "width": clean[1], "height": clean[2]}
        attachments.append(entry)
    return {
        "subject": message.subject or "",
        "sender": message.from_values.full if message.from_values else message.from_,
        "from": message.from_ or "",
        "date": date.isoformat() if date else None,
        "headers": {name: headers[name] for name in KEPT_HEADERS if name in headers},
        "body": body,
        "attachments": attachments,
    }


def main() -> None:
    raw = sys.stdin.buffer.read(MAX_INPUT_BYTES + 1)
    try:
        reply = {"error": "too large"} if len(raw) > MAX_INPUT_BYTES else parse(raw)
    except Exception as error:  # noqa: BLE001 - any failure is reported, never raised into a traceback
        reply = {"error": type(error).__name__}
    sys.stdout.buffer.write(json.dumps(reply, ensure_ascii=False).encode())
    sys.stdout.buffer.flush()


# ---- in the watcher -----------------------------------------------------------------------------------

# The only segments our encoder writes: JFIF header, quantisation tables, baseline frame, Huffman tables.
JPEG_SEGMENTS = {0xE0, 0xDB, 0xC0, 0xC4}


def is_clean_jpeg(data: bytes, width: int, height: int) -> bool:
    """Whether `data` has exactly the shape clean_image() produces. Read without decoding anything, so a
    sandbox that was taken over cannot pass the phone an image with metadata, extra segments, several
    scans, the wrong size, or a second file hidden after its end."""
    if len(data) < 4 or not data.startswith(b"\xff\xd8") or not data.endswith(b"\xff\xd9"):
        return False
    at, sized = 2, False
    while at + 4 <= len(data):
        if data[at] != 0xFF:
            return False
        marker, length = data[at + 1], int.from_bytes(data[at + 2 : at + 4], "big")
        if length < 2 or at + 2 + length > len(data) - 2:
            return False
        segment = data[at + 4 : at + 2 + length]
        if marker == 0xDA:  # start of scan: entropy-coded data runs to the end marker
            scan = data[at + 2 + length : -2]
            found = scan.find(b"\xff")
            while found != -1:  # inside a scan an FF byte is only ever stuffing (FF00) or a restart (FFD0-D7)
                follower = scan[found + 1] if found + 1 < len(scan) else None
                if follower is None or not (follower == 0x00 or 0xD0 <= follower <= 0xD7):
                    return False
                found = scan.find(b"\xff", found + 2)
            return sized
        if marker not in JPEG_SEGMENTS or (marker == 0xE0 and not segment.startswith(b"JFIF\x00")):
            return False
        if marker == 0xC0:
            if len(segment) < 6:
                return False
            frame = int.from_bytes(segment[3:5], "big"), int.from_bytes(segment[1:3], "big")
            sized = frame == (width, height) and segment[5] == 3
        at += 2 + length
    return False


def _text(reply: dict[str, Any], name: str, limit_name: str | None = None) -> str:
    value = reply.get(name) or ""
    if not isinstance(value, str):
        raise MailParseError(f"{name} is not text")
    return value[: TEXT_LIMITS[limit_name or name]]


def from_reply(reply: Any) -> ParsedMail:
    """Checks what the sandbox sent back. A sandbox that was taken over could send anything, so the
    reply is held to the same shape and limits a healthy one produces."""
    import hashlib

    if not isinstance(reply, dict):
        raise MailParseError("reply is not an object")
    if "error" in reply:
        raise MailParseError(f"the parser failed: {str(reply['error'])[:100]}")
    date = None
    if reply.get("date"):
        try:
            date = datetime.fromisoformat(_text(reply, "date", "name"))
        except ValueError:
            date = None
    headers_in = reply.get("headers") or {}
    if not isinstance(headers_in, dict):
        raise MailParseError("headers is not an object")
    headers = {k: str(v)[:500] for k, v in headers_in.items() if k in KEPT_HEADERS}

    attachments: list[Attachment] = []
    images: dict[str, bytes] = {}
    entries = reply.get("attachments") or []
    if not isinstance(entries, list):
        raise MailParseError("attachments is not a list")
    for entry in entries[:MAX_ATTACHMENTS]:
        if not isinstance(entry, dict):
            continue
        size = entry.get("size") if isinstance(entry.get("size"), int) else 0
        image, width, height = None, 0, 0
        if isinstance(entry.get("jpeg"), str) and len(images) < MAX_IMAGES:
            try:
                data = base64.b64decode(entry["jpeg"], validate=True)
            except (binascii.Error, ValueError):
                data = b""
            sides = entry.get("width"), entry.get("height")
            if (
                len(data) <= MAX_IMAGE_BYTES
                and all(isinstance(side, int) and 0 < side <= IMAGE_SIDE for side in sides)
                and is_clean_jpeg(data, *sides)  # type: ignore[arg-type]
            ):
                image = hashlib.sha256(data).hexdigest()
                images[image] = data
                width, height = sides  # type: ignore[assignment]
        attachments.append(Attachment(_text(entry, "name"), _text(entry, "type"), size, image, width, height))
    return ParsedMail(
        subject=_text(reply, "subject"),
        sender=_text(reply, "sender"),
        from_=_text(reply, "from"),
        date=date,
        body=_text(reply, "body"),
        headers=headers,
        attachments=tuple(attachments),
        images=images,
    )


Parser = Callable[[bytes], ParsedMail]


class SandboxedParser:
    """Hands one raw mail to the socket-activated sandbox and reads its answer."""

    def __init__(self, path: str, timeout: float = 60.0):
        self.path = path
        self.timeout = timeout

    def __call__(self, raw: bytes) -> ParsedMail:
        chunks: list[bytes] = []
        total = 0
        try:
            with socket.socket(socket.AF_UNIX, socket.SOCK_STREAM) as connection:
                connection.settimeout(self.timeout)
                try:
                    connection.connect(self.path)
                except OSError as error:
                    raise SandboxUnavailable(f"the mail sandbox is unreachable: {error}") from error
                connection.sendall(raw)
                connection.shutdown(socket.SHUT_WR)
                while chunk := connection.recv(1 << 16):
                    total += len(chunk)
                    if total > MAX_REPLY_BYTES:
                        raise MailParseError("the parser's reply is too large")
                    chunks.append(chunk)
        except SandboxUnavailable:
            raise
        except OSError as error:
            raise MailParseError(f"the parser connection broke: {error}") from error
        if not chunks:
            raise MailParseError("the parser stopped without an answer (time or memory limit)")
        try:
            return from_reply(json.loads(b"".join(chunks)))
        except json.JSONDecodeError as error:
            raise MailParseError("the parser's reply is not JSON") from error


def parse_here(raw: bytes) -> ParsedMail:
    """Parses in this process, unsandboxed. For tests and development only."""
    return from_reply(json.loads(json.dumps(parse(raw))))


if __name__ == "__main__":
    main()
